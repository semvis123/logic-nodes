<script lang="ts">
	import { SITE } from '$lib/site';
	import ContentPage from '$lib/ContentPage.svelte';
	import { modifiedFields } from '$lib/lastmod';
	import {
		parseRadix,
		placeValueSteps,
		divisionSteps,
		toRadix,
		groupDigits,
		groupDecimal,
		hexDigitTable,
		superscript,
		RadixError,
		MAX_DIGITS
	} from '$lib/radix';
	import { readUrl, syncUrl, safeText, safeOption } from '$lib/urlState';
	import ShareLink from '$lib/ShareLink.svelte';
	import { onMount } from 'svelte';

	type Direction = 'hex' | 'dec';
	const DEFAULTS = { v: 'BEEF', from: 'hex' };
	onMount(() => {
		const p = readUrl();
		input = safeText(p.v, MAX_DIGITS + 10) ?? input;
		from = safeOption(p.from, ['hex', 'dec'] as const) ?? from;
	});
	$: syncUrl({ v: input, from }, DEFAULTS);

	let input = DEFAULTS.v;
	let from: Direction = 'hex';

	// Runs at build time too, so the page ships with a real worked conversion.
	let value = 0n;
	let digits = '';
	let error = '';
	$: {
		try {
			const parsed = parseRadix(input, from === 'hex' ? 16 : 10);
			value = parsed.value;
			digits = parsed.digits.replace(/^0+(?=.)/, '');
			error = '';
		} catch (e) {
			error = e instanceof RadixError ? e.message : 'That is not a number';
		}
	}
	$: hex = toRadix(value, 16);
	$: places = placeValueSteps(from === 'hex' ? digits : hex, 16);
	$: division = divisionSteps(value, 16);

	/** Switching direction carries the answer across, so the reverse is one click away. */
	function swap() {
		if (!error) input = from === 'hex' ? value.toString() : hex;
		from = from === 'hex' ? 'dec' : 'hex';
	}

	function tryValue(v: string, direction: Direction) {
		from = direction;
		input = v;
		const field = document.getElementById('value');
		field?.scrollIntoView({ behavior: 'smooth', block: 'center' });
		field?.focus({ preventScroll: true });
	}

	const examples: { label: string; v: string; from: Direction }[] = [
		{ label: 'FF', v: 'FF', from: 'hex' },
		{ label: '#1E90FF', v: '#1E90FF', from: 'hex' },
		{ label: '7FFFFFFF', v: '7FFFFFFF', from: 'hex' },
		{ label: '0xDEADBEEF', v: '0xDEADBEEF', from: 'hex' },
		{ label: '255 to hex', v: '255', from: 'dec' },
		{ label: '1000 to hex', v: '1000', from: 'dec' },
		{ label: '65535 to hex', v: '65535', from: 'dec' }
	];

	const dec = (n: bigint) => groupDecimal(n.toString());
	/** A sum written out: 11×16³ + 14×16² + … */
	const termText = (t: { value: number; power: number }) => `${t.value}×16${superscript(t.power)}`;

	// Worked examples, generated by the same engine as the converter.
	const ff = placeValueSteps('FF', 16);
	const worked1 = placeValueSteps('1A3', 16);
	const worked2 = divisionSteps(1000n, 16);
	const colour = { r: parseRadix('1E', 16).value, g: parseRadix('90', 16).value, b: parseRadix('FF', 16).value };
	const powers = Array.from({ length: 9 }, (_, n) => ({ n, value: 16n ** BigInt(n) }));

	const faqs = [
		{
			q: 'What is FF in decimal?',
			a: `FF is ${ff.total}. The left F is worth ${ff.terms[0].value} × 16 = ${ff.terms[0].product} and the right F is worth ${ff.terms[1].value} × 1 = ${ff.terms[1].product}, and ${ff.terms[0].product} + ${ff.terms[1].product} = ${ff.total}. It is the largest value one byte can hold, which is why it turns up in colour codes and masks.`
		},
		{
			q: 'How do I convert hex to decimal by hand?',
			a: 'Number the digits from the right starting at 0. Multiply each digit by 16 to the power of its position, using A = 10, B = 11, C = 12, D = 13, E = 14 and F = 15, then add the results. For 1A3 that is 1×256 + 10×16 + 3×1 = 419.'
		},
		{
			q: 'How do I convert decimal to hex?',
			a: 'Divide the number by 16 and write down the remainder, then divide the quotient by 16 again, and keep going until the quotient is 0. Write each remainder as a hex digit (10 is A, 15 is F) and read them from the last one to the first. 1000 gives remainders 8, 14 and 3, so it is 3E8.'
		},
		{
			q: 'What does 0x mean in front of a number?',
			a: 'It marks the number as hexadecimal in C, JavaScript, Python and most other languages, so 0x10 is sixteen and not ten. CSS writes a # instead for colours, and some assemblers use a trailing h or a leading $. The converter accepts 0x, # and $ and ignores them.'
		},
		{
			q: 'How big a number can this convert?',
			a: `Up to ${MAX_DIGITS} digits of either base, which is 256 bits in hex. The arithmetic uses whole numbers of any size, so nothing is rounded the way it would be in a spreadsheet past about 15 digits. Negative numbers and fractions are not converted here; a negative number needs a fixed width, which the two's complement page covers.`
		},
		{
			q: 'Why is hexadecimal base 16?',
			a: 'Because 16 is 2 to the power 4, so one hex digit stands for exactly four bits. That makes converting between hex and binary a matter of looking up each digit, while still writing a byte in two characters instead of eight.'
		}
	];

	const page = {
		title: 'Hex to Decimal Converter (and Decimal to Hex), With Steps',
		description:
			'Convert hex to decimal and decimal to hex with every step shown: place values for hex to decimal, repeated division by 16 for decimal to hex.',
		url: `${SITE}/hex-to-decimal`,
		image: `${SITE}/og/hex-to-decimal.png`,
		imageAlt: 'LogicGates.org: hex to decimal converter with steps'
	};

	const jsonLd = `<script type="application/ld+json">${JSON.stringify({
		'@context': 'https://schema.org',
		'@graph': [
			{
				'@type': ['WebPage', 'FAQPage'],
				'@id': `${page.url}#webpage`,
				url: page.url,
				name: page.title,
				description: page.description,
				isPartOf: { '@id': `${SITE}/#website` },
				breadcrumb: { '@id': `${page.url}#breadcrumb` },
				inLanguage: 'en',
				...modifiedFields(page.url),
				mainEntity: faqs.map((f) => ({
					'@type': 'Question',
					name: f.q,
					acceptedAnswer: { '@type': 'Answer', text: f.a }
				}))
			},
			{
				'@type': 'BreadcrumbList',
				'@id': `${page.url}#breadcrumb`,
				itemListElement: [
					{ '@type': 'ListItem', position: 1, name: 'LogicGates.org', item: `${SITE}/` },
					{ '@type': 'ListItem', position: 2, name: 'Tools', item: `${SITE}/tools` },
					{ '@type': 'ListItem', position: 3, name: 'Hex to decimal converter' }
				]
			}
		]
	})}${'<'}/script>`;
</script>

