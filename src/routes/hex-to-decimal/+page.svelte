		<div class="card tool">
			<div class="direction" role="group" aria-label="Direction">
				<button
					type="button"
					class:active={from === 'hex'}
					aria-pressed={from === 'hex'}
					on:click={() => from !== 'hex' && swap()}>Hex to decimal</button
				>
				<button
					type="button"
					class:active={from === 'dec'}
					aria-pressed={from === 'dec'}
					on:click={() => from !== 'dec' && swap()}>Decimal to hex</button
				>
			</div>

			<label class="field" for="value">{from === 'hex' ? 'Hex number' : 'Decimal number'}</label>
			<input
				id="value"
				class="value-input"
				type="text"
				bind:value={input}
				spellcheck="false"
				autocomplete="off"
				autocapitalize="off"
				inputmode={from === 'dec' ? 'numeric' : 'text'}
				aria-invalid={error ? 'true' : 'false'}
				aria-describedby="value-help"
			/>
			{#if error}
				<p class="error" role="alert">{error}</p>
			{/if}
			<p class="field-help" id="value-help">
				{#if from === 'hex'}
					Digits 0 to 9 and A to F, upper or lower case. A leading 0x, # or $ is ignored, and so are spaces.
				{:else}
					A whole number of zero or more, up to {MAX_DIGITS} digits.
				{/if}
			</p>

			<div class="chips">
				{#each examples as example}
					<button type="button" class="chip-btn" on:click={() => tryValue(example.v, example.from)}>
						{example.label}
					</button>
				{/each}
			</div>

			<div class="results" class:stale={!!error} aria-hidden={error ? 'true' : 'false'}>
				<div class="answer" role={error ? undefined : 'status'}>
					<span class="answer-label">{from === 'hex' ? 'Decimal' : 'Hex'}</span>
					<span class="answer-value mono">{from === 'hex' ? dec(value) : hex}</span>
					<span class="answer-also"
						>{from === 'hex' ? `${hex} in hex` : `${dec(value)} in decimal`} is
						<span class="mono">{groupDigits(value.toString(2), 4)}</span> in binary</span
					>
				</div>

				{#if from === 'hex'}
					<h3 class="working-title">Working: each digit times its place value</h3>
					<div class="table-wrap scroll-box">
						<table class="data-table steps">
							<thead>
								<tr>
									<th scope="col">Digit</th>
									<th scope="col">Value</th>
									<th scope="col">Place</th>
									<th scope="col" class="num">Place value</th>
									<th scope="col" class="num">Digit × place</th>
								</tr>
							</thead>
							<tbody>
								{#each places.terms as term}
									<tr>
										<td class="mono strong">{term.digit}</td>
										<td class="mono">{term.value}</td>
										<td class="mono">16{superscript(term.power)}</td>
										<td class="mono num">{dec(term.place)}</td>
										<td class="mono num">{dec(term.product)}</td>
									</tr>
								{/each}
								<tr class="total">
									<th scope="row" colspan="4">Sum</th>
									<td class="mono num strong">{dec(places.total)}</td>
								</tr>
							</tbody>
						</table>
					</div>
					{#if places.terms.length <= 8}
						<p class="equation mono">
							{places.terms.map(termText).join(' + ')}<br />= {places.terms.map((t) => dec(t.product)).join(' + ')}<br
							/>= {dec(places.total)}
						</p>
					{/if}
				{:else}
					<h3 class="working-title">Working: divide by 16, keep the remainders</h3>
					<div class="table-wrap scroll-box">
						<table class="data-table steps">
							<thead>
								<tr>
									<th scope="col" class="num">Number</th>
									<th scope="col" class="num">÷ 16</th>
									<th scope="col">Remainder</th>
									<th scope="col">Hex digit</th>
								</tr>
							</thead>
							<tbody>
								{#each division.steps as step}
									<tr>
										<td class="mono num">{dec(step.dividend)}</td>
										<td class="mono num">{dec(step.quotient)}</td>
										<td class="mono">{step.remainder}</td>
										<td class="mono strong">{step.digit}</td>
									</tr>
								{/each}
							</tbody>
						</table>
					</div>
					<p class="equation">
						Read the hex digits from the bottom up: <span class="mono strong">{division.result}</span>. The first
						remainder is the last digit, because it is the part left over after taking out every whole 16.
					</p>
				{/if}
			</div>
			<p class="share-row"><ShareLink what="this conversion" /></p>
		</div>
	</section>

	<section id="what-is-hex">
		<h2>What hexadecimal is</h2>
		<p>
			Hexadecimal, or hex, is base 16. Decimal runs out of digits at 9 and carries into the tens column; hex keeps going
			with six letters, A to F for ten to fifteen, and only carries at sixteen. So 10 in hex is sixteen, 100 is 16 × 16
			= 256, and FF is the largest two digit value, 255.
		</p>
		<div class="table-wrap">
