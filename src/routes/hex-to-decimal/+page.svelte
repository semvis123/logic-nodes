	<section id="why">
		<h2>Why programmers use hex</h2>
		<ul class="points">
			<li>
				<strong>Four bits per digit.</strong> Sixteen is 2<sup>4</sup>, so each hex digit is exactly one group of four
				bits, a nibble. Converting to binary is a lookup, digit by digit, with no arithmetic; the
				<a href="/hex-to-binary">hex to binary converter</a> shows it.
			</li>
			<li>
				<strong>A byte is two digits.</strong> Eight bits always fit in 00 to FF, so memory dumps, network packets and file
				formats line up in neat pairs. The same byte in decimal takes one to three digits and does not line up.
			</li>
			<li>
				<strong>Colours.</strong> A CSS colour such as
				<span class="swatch" style="background:#1E90FF" aria-hidden="true" />
				<span class="mono">#1E90FF</span> is three bytes: red 1E = {colour.r}, green 90 = {colour.g} and blue FF =
				{colour.b}.
			</li>
			<li>
				<strong>Memory addresses and masks.</strong> An address like 0x7FFF0010 or a mask like 0xFF00 is easier to read and
				check in hex, because you can see which bits are set without converting anything.
			</li>
		</ul>
	</section>

